"""Export a compact Random Forest as JSON/JS so the static app can run it in the browser (no server needed).
Writes docs/model.js and tests_js/parity.json (Python's answers, used to check the JS port).
Run:  python export_edge_model.py"""
import json
from pathlib import Path

import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, f1_score, recall_score
from sklearn.model_selection import train_test_split

from app import service
from app.core import FEATURES, LABELS
from app.ml import Predictor
from app.simulate import build_dataset, simulate_readings

OUT = Path("docs")
N_TREES, DEPTH, LEAF = 40, 8, 5

df = build_dataset(6000, 42)
y = df["label"].map({l: i for i, l in enumerate(LABELS)})
Xtr, Xte, ytr, yte = train_test_split(df[FEATURES], y, test_size=0.2, stratify=y, random_state=42)
rf = RandomForestClassifier(n_estimators=N_TREES, max_depth=DEPTH, min_samples_leaf=LEAF, random_state=42, n_jobs=-1).fit(Xtr, ytr)
pred = rf.predict(Xte)
metrics = {"accuracy": round(accuracy_score(yte, pred), 4), "f1_macro": round(f1_score(yte, pred, average="macro"), 4),
           "recall_high": round(recall_score(yte, pred, labels=[2], average="macro"), 4)}
print("compact forest:", metrics)

trees = []
for est in rf.estimators_:
    t = est.tree_
    leaf = t.children_left == -1
    val = t.value[:, 0, :]
    val = val / val.sum(axis=1, keepdims=True)
    trees.append({"f": [int(a) for a in t.feature], "t": [round(float(a), 6) for a in t.threshold],
                  "l": [int(a) for a in t.children_left], "r": [int(a) for a in t.children_right],
                  "p": [[round(float(v), 4) for v in val[i]] if leaf[i] else 0 for i in range(t.node_count)]})
model = {"name": f"Random Forest ({N_TREES} trees, compact)", "features": FEATURES,
         "background": {k: round(float(v), 6) for k, v in Xtr.mean().items()}, "metrics": metrics, "trees": trees}
OUT.mkdir(parents=True, exist_ok=True)
(OUT / "model.js").write_text("// generated by export_edge_model.py - do not edit\nexport const MODEL = " + json.dumps(model, separators=(",", ":")) + ";\n")
print("nodes:", sum(len(t["f"]) for t in trees), "| model.js KB:", (OUT / "model.js").stat().st_size // 1024)

# Python's answers for 60 random histories + 3 hand-made ones, to check the JS port against
bundle = {"name": model["name"], "model": rf, "features": FEATURES, "background": model["background"], "metrics": {model["name"]: metrics}}
pr = Predictor(bundle)
rng = np.random.default_rng(123)
cases = []
for i in range(60):
    readings, end = simulate_readings(rng)
    cases.append(("chicken" if i % 2 else "rice", end, readings))
cases += [("chicken", 3.0, [(0.0, 28.0), (1.0, 31.0), (2.0, 30.0)]), ("chicken", 3.0, [(0.0, 4.0), (170 / 60, 25.0)]), ("rice", 3.0, [(0.0, 25.0)])]
out = []
for food, end, readings in cases:
    r = service.assess(pr, food, end, readings)
    out.append({"food": food, "total_hours": end, "readings": [list(x) for x in readings], "label": r["label"],
                "probabilities": r["probabilities"], "features": r["features"], "reference": r["reference"],
                "recommendation": r["recommendation"]})
(Path("tests_js") / "parity.json").write_text(json.dumps(out))
print("parity cases:", len(out), "| labels:", {l: sum(c["label"] == l for c in out) for l in LABELS})
